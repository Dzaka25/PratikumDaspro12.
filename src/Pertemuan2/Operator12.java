
public class Operator12 {
    public static void main(String[] args) {
        int a=60;
        int b=20;
        int c=10;

        System.err.println("Aritmetika Operator");
        System.out.println("Bilangan a adalah "+a);
        System.err.println("Bilangan b adalah "+b);
        System.err.println("Bilangan c adalah "+c);     
        System.err.println("a + b + c = "+(a+b+c));     
        System.err.println("a - b - c = "+(a-b-c));     
        System.err.println("a * c = "+(a*c));     
        System.err.println("a / b = "+(a/b));     
        System.err.println("a % b = "+(a%b));     
        System.err.println("a + b * c = "+(a+b*c));     
        System.err.println("(a + b) * c = "+(a+b)*c);     
    }
}